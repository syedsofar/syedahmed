import { useEffect, useRef, useState } from 'react';
import { FileText, FileDown, FileSpreadsheet, RefreshCw, Save } from 'lucide-react';
import { api, downloadBlob } from '../lib/api';
import { useProject } from '../lib/project';
import { Badge, Callout, Field, useToast } from '../components/ui';
import { DiagramSvg, svgToPng } from '../components/DiagramSvg';
import { REPORT_TYPES, type Block, type ReportDoc, type ReportType } from '@shared/report';
import type { ArchitectureModel, ModelVersion, ProjectData } from '@shared/types';

export function ReportsPage() {
  const { data, can, mutate } = useProject();
  const toast = useToast();
  const [type, setType] = useState<ReportType>('architecture_review');
  const [doc, setDoc] = useState<ReportDoc | null>(null);
  const [busy, setBusy] = useState<string>('');
  const [snapshot, setSnapshot] = useState<{ model: ArchitectureModel; label: string } | null>(null);
  const [narr, setNarr] = useState(data.project.narrative);
  const svgRef = useRef<SVGSVGElement>(null);
  const dirty = JSON.stringify(narr) !== JSON.stringify(data.project.narrative);

  const latest = data.versions[data.versions.length - 1];
  useEffect(() => {
    if (!latest) { setSnapshot({ model: data.model, label: 'working model (no saved version)' }); return; }
    api.get<ModelVersion>(`/projects/${data.project.id}/versions/${latest.version}`).then((v) => setSnapshot({ model: v.model, label: `model v${v.version}` })).catch(() => setSnapshot({ model: data.model, label: 'working model' }));
  }, [latest?.version]);

  const refresh = async () => {
    try { setDoc(await api.post<ReportDoc>(`/projects/${data.project.id}/report-preview`, { type })); } catch (e) { toast.error(e); }
  };
  useEffect(() => { refresh(); }, [type, data.project.updatedAt]);

  const exportAs = async (format: 'docx' | 'pdf' | 'xlsx') => {
    setBusy(format);
    try {
      const diagramPng = format !== 'xlsx' && svgRef.current ? await svgToPng(svgRef.current) : undefined;
      const blob = await api.blob(`/projects/${data.project.id}/export`, { type, format, diagramPng });
      const name = `${data.project.clientAlias}-${type}-${new Date().toISOString().slice(0, 10)}${data.project.isDemo ? '-DEMO' : ''}.${format}`.replace(/[^\w.-]/g, '_');
      downloadBlob(blob, name);
      toast.ok(`${format.toUpperCase()} generated by the reporting service.`);
    } catch (e) { toast.error(e); } finally { setBusy(''); }
  };

  return (
    <div className="page">
      <div className="page-head">
        <div><h1>Reporting</h1><div className="sub">Reports are generated from the stored assessment by the backend reporting service (DOCX, PDF, Excel). The preview below uses the same document structure as the exports.</div></div>
        <div className="actions">
          <button className="btn" onClick={refresh}><RefreshCw size={16} /> Refresh preview</button>
          {can('report:export') ? <>
            <button className="btn btn-primary" disabled={!!busy} onClick={() => exportAs('docx')}><FileText size={16} /> {busy === 'docx' ? 'Generating…' : 'DOCX'}</button>
            <button className="btn btn-primary" disabled={!!busy} onClick={() => exportAs('pdf')}><FileDown size={16} /> {busy === 'pdf' ? 'Generating…' : 'PDF'}</button>
            <button className="btn btn-teal" disabled={!!busy} onClick={() => exportAs('xlsx')}><FileSpreadsheet size={16} /> {busy === 'xlsx' ? 'Generating…' : 'Excel'}</button>
          </> : <Badge>Export requires analyst role and project edit access</Badge>}
        </div>
      </div>

      <div className="grid grid-4">
        {(Object.keys(REPORT_TYPES) as ReportType[]).map((t) => (
          <button key={t} className="card card-pad" style={{ textAlign: 'left', cursor: 'pointer', borderColor: type === t ? 'var(--teal-600)' : undefined, boxShadow: type === t ? '0 0 0 2px var(--teal-600)' : undefined }} onClick={() => setType(t)}>
            <strong style={{ color: 'var(--navy-800)' }}>{REPORT_TYPES[t].title}</strong>
            <div className="small muted" style={{ marginTop: 4 }}>{REPORT_TYPES[t].description}</div>
          </button>
        ))}
      </div>

      <div className="split" style={{ marginTop: 16 }}>
        <div>
          {data.project.status !== 'final' && <Callout tone="warn">This assessment is not final ({data.project.status.replace('_', ' ')}). Exports are watermarked with the current status in the metadata.</Callout>}
          <div style={{ marginTop: 12 }}>{doc ? <ReportView doc={doc} snapshot={snapshot} /> : <div className="loading">Building preview…</div>}</div>
        </div>
        <aside className="card drawer">
          <div className="card-head"><h2>Reviewer narrative</h2></div>
          <div className="card-body stack">
            <p className="small muted">Optional text written by the reviewer. Generated sections (statistics, findings, limitations) are always included and cannot be overwritten here.</p>
            <Field label="Executive summary"><textarea rows={6} value={narr.executiveSummary} disabled={!can('project:edit')} onChange={(e) => setNarr({ ...narr, executiveSummary: e.target.value })} /></Field>
            <Field label="Additional limitations"><textarea rows={4} value={narr.limitations} disabled={!can('project:edit')} onChange={(e) => setNarr({ ...narr, limitations: e.target.value })} /></Field>
            <Field label="Additional recommendations"><textarea rows={4} value={narr.recommendations} disabled={!can('project:edit')} onChange={(e) => setNarr({ ...narr, recommendations: e.target.value })} /></Field>
            {can('project:edit') && <div><button className="btn btn-primary btn-sm" disabled={!dirty} onClick={() => mutate(() => api.patch<ProjectData>(`/projects/${data.project.id}`, { narrative: narr }), 'Narrative saved.')}><Save size={14} /> Save narrative</button></div>}
            <p className="small muted">Architecture snapshot source: {snapshot?.label ?? '…'}</p>
          </div>
        </aside>
      </div>
      {/* Off-screen diagram used to rasterise the architecture snapshot for DOCX/PDF exports. */}
      <div style={{ position: 'absolute', left: -10000, top: 0 }} aria-hidden>{snapshot && <DiagramSvg ref={svgRef} model={snapshot.model} />}</div>
    </div>
  );
}

function ReportView({ doc, snapshot }: { doc: ReportDoc; snapshot: { model: ArchitectureModel; label: string } | null }) {
  return (
    <article className="report-paper">
      <div className={`classif ${doc.isDemo ? 'demo' : ''}`}>{doc.isDemo ? 'DEMONSTRATION DATA — SYNTHETIC — NOT FOR CLIENT USE' : 'CONFIDENTIAL — Internal security assessment'}</div>
      <h1>{doc.title}</h1>
      <div className="subtitle">{doc.subtitle}</div>
      <table className="kvt"><tbody>{doc.meta.map(([k, v]) => <tr key={k}><td>{k}</td><td>{v}</td></tr>)}</tbody></table>
      {doc.sections.map((s, i) => (
        <section key={i}>
          <h2>{s.heading}</h2>
          {s.blocks.map((b, j) => <BlockView key={j} b={b} snapshot={snapshot} />)}
        </section>
      ))}
    </article>
  );
}

function BlockView({ b, snapshot }: { b: Block; snapshot: { model: ArchitectureModel } | null }) {
  switch (b.type) {
    case 'p': return <p>{b.text}</p>;
    case 'bullets': return <ul>{b.items.map((x, i) => <li key={i}>{x}</li>)}</ul>;
    case 'callout': return <div className={`callout callout-${b.tone === 'warn' ? 'warn' : 'info'}`} style={{ margin: '8px 0' }}>{b.text}</div>;
    case 'kv': return <table className="kvt"><tbody>{b.rows.map(([k, v], i) => <tr key={i}><td>{k}</td><td>{v}</td></tr>)}</tbody></table>;
    case 'table': return b.rows.length ? (
      <div className="table-wrap"><table><thead><tr>{b.columns.map((c) => <th key={c}>{c}</th>)}</tr></thead><tbody>{b.rows.map((r, i) => <tr key={i}>{r.map((c, j) => <td key={j}>{c}</td>)}</tr>)}</tbody></table></div>
    ) : <p className="muted"><em>No entries.</em></p>;
    case 'image': return snapshot ? <figure style={{ margin: '8px 0' }}><div style={{ overflow: 'auto', border: '1px solid var(--line)' }}><DiagramSvg model={snapshot.model} scale={0.55} /></div><figcaption className="small muted" style={{ textAlign: 'center' }}>{b.caption}</figcaption></figure> : null;
  }
}
