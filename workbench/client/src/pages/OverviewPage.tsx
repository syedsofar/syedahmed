import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Save, CheckCircle2, Circle, Users, History, ScrollText } from 'lucide-react';
import { api } from '../lib/api';
import { useAuth } from '../lib/auth';
import { useProject } from '../lib/project';
import { Badge, Callout, Field, Modal, Stat, fmtDate, useToast } from '../components/ui';
import { ProjectForm, type ProjectFormValue } from '../components/ProjectForm';
import { ROLE_LABELS, STATUS_LABELS } from '@shared/schema';
import type { AssessmentStatus, AuditEntry, ProjectData, ProjectMember } from '@shared/types';
import { STATUS_TONE } from './DashboardPage';

const FLOW: AssessmentStatus[] = ['draft', 'in_review', 'pending_approval', 'final', 'archived'];

export function OverviewPage() {
  const { data, can, mutate } = useProject();
  const { userName, users, can: globalCan } = useAuth();
  const toast = useToast();
  const p = data.project;
  const toForm = (): ProjectFormValue => ({ name: p.name, clientAlias: p.clientAlias, scope: p.scope, architectureVersion: p.architectureVersion, reviewerId: p.reviewerId, reviewDate: p.reviewDate, methodologies: p.methodologies, catalogIds: p.catalogIds });
  const [form, setForm] = useState<ProjectFormValue>(toForm);
  const [members, setMembers] = useState<ProjectMember[] | null>(null);
  const [audit, setAudit] = useState<AuditEntry[] | null>(null);
  useEffect(() => setForm(toForm()), [data.project.updatedAt]);

  const dirty = JSON.stringify(form) !== JSON.stringify(toForm());
  const save = () => mutate(() => api.patch<ProjectData>(`/projects/${p.id}`, form), 'Assessment details saved.');
  const setStatus = (status: AssessmentStatus) => mutate(() => api.patch<ProjectData>(`/projects/${p.id}`, { status }), `Status set to ${STATUS_LABELS[status]}.`);

  const unconfirmed = data.model.components.filter((c) => c.status !== 'confirmed').length + data.model.flows.filter((f) => f.status !== 'confirmed').length + data.model.zones.filter((z) => z.status !== 'confirmed').length;
  const lastVersion = data.versions[data.versions.length - 1];
  const lastRun = data.runs[data.runs.length - 1];
  const proposed = data.threats.filter((t) => t.decision === 'proposed').length;
  const live = data.threats.filter((t) => t.decision !== 'rejected');
  const steps = [
    { done: data.model.components.length > 0, label: 'Capture the architecture (draw or import)', to: 'architecture' },
    { done: data.model.components.length > 0 && unconfirmed === 0, label: unconfirmed ? `Confirm ${unconfirmed} imported element(s)` : 'All model elements confirmed', to: 'imports' },
    { done: !!lastVersion, label: lastVersion ? `Model saved as v${lastVersion.version}` : 'Save a model version', to: 'architecture' },
    { done: !!lastRun && lastRun.modelVersion === lastVersion?.version, label: lastRun ? (lastRun.modelVersion === lastVersion?.version ? `Analysis run on v${lastRun.modelVersion}` : `Re-run analysis (last run on v${lastRun.modelVersion})`) : 'Run threat analysis', to: 'threats' },
    { done: !!lastRun && proposed === 0, label: proposed ? `Review ${proposed} proposed threat(s)` : 'Generated threats reviewed', to: 'threats' },
    { done: data.controlReviews.length > 0, label: 'Record control review outcomes', to: 'controls' },
    { done: data.risks.length > 0 && data.risks.every((r) => r.approval.state === 'approved'), label: data.risks.length ? `${data.risks.filter((r) => r.approval.state === 'approved').length}/${data.risks.length} risks approved` : 'Register and approve risks', to: 'risks' },
    { done: p.status === 'final', label: 'Finalise and export reports', to: 'reports' },
  ];

  const loadAudit = () => api.get<AuditEntry[]>(`/audit?projectId=${p.id}`).then(setAudit).catch(toast.error);

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <div className="row gap wrap"><h1>{p.name}</h1><Badge tone={STATUS_TONE[p.status]}>{STATUS_LABELS[p.status]}</Badge>{p.isDemo && <Badge tone="demo">DEMONSTRATION DATA</Badge>}</div>
          <div className="sub">{p.clientAlias} · created {fmtDate(p.createdAt)} by {userName(p.createdBy)} · your project role: <strong>{data.myRole}</strong></div>
        </div>
        <div className="actions">
          <button className="btn" onClick={loadAudit}><ScrollText size={16} /> Project audit trail</button>
          {can('member:manage') && <button className="btn" onClick={() => setMembers(p.members)}><Users size={16} /> Members</button>}
        </div>
      </div>
      {p.isDemo && <Callout tone="warn">This assessment contains synthetic demonstration data. It does not describe any real organisation. Its threats were generated by the rule engine from the synthetic model.</Callout>}

      <div className="grid grid-4" style={{ marginTop: 14 }}>
        <Stat label="Model" value={lastVersion ? `v${lastVersion.version}` : '—'} sub={`${data.model.components.length} components · ${data.model.flows.length} flows · ${data.model.zones.length} zones`} />
        <Stat label="Confirmed findings" tone="danger" value={live.filter((t) => t.classification === 'confirmed').length} sub={`${proposed} awaiting analyst review`} />
        <Stat label="Hypotheses / missing evidence" tone="warn" value={`${live.filter((t) => t.classification === 'hypothesis').length} / ${live.filter((t) => t.classification === 'missing_evidence').length}`} />
        <Stat label="Risks" tone="teal" value={data.risks.length} sub={`${data.risks.filter((r) => r.approval.state !== 'approved').length} awaiting approval`} />
      </div>

      <div className="split" style={{ marginTop: 16 }}>
        <div className="stack-l">
          <section className="card">
            <div className="card-head"><h2>Assessment details</h2>
              <div className="right row gap">{can('project:edit') && <button className="btn btn-primary btn-sm" disabled={!dirty} onClick={save}><Save size={14} /> Save details</button>}</div>
            </div>
            <div className="card-body"><ProjectForm value={form} onChange={setForm} disabled={!can('project:edit')} /></div>
          </section>

          <section className="card">
            <div className="card-head"><h2>Assessment status</h2></div>
            <div className="card-body stack">
              <div className="row gap wrap">
                {FLOW.map((s) => (
                  <button key={s} className={`btn btn-sm ${p.status === s ? 'btn-primary' : ''}`} disabled={!can('project:edit') || p.status === s || ((s === 'final' || p.status === 'final') && !globalCan('risk:approve'))} onClick={() => setStatus(s)}>{STATUS_LABELS[s]}</button>
                ))}
              </div>
              <p className="muted small">Finalising requires a lead reviewer and all registered risks approved. Archived assessments are read-only until re-opened.</p>
            </div>
          </section>

          <section className="card">
            <div className="card-head"><History size={16} /><h2>Model versions</h2></div>
            {data.versions.length === 0 ? <div className="card-body muted">No saved versions. Save one from the Architecture editor.</div> : (
              <div className="table-wrap"><table className="table"><thead><tr><th>Version</th><th>Message</th><th>Saved</th><th>Hash</th></tr></thead><tbody>
                {[...data.versions].reverse().map((v) => <tr key={v.version}><td><strong>v{v.version}</strong></td><td>{v.message}</td><td className="small nowrap">{fmtDate(v.savedAt)} · {userName(v.savedBy)}</td><td className="mono">{v.hash.slice(0, 12)}</td></tr>)}
              </tbody></table></div>
            )}
          </section>
        </div>

        <div className="stack-l">
          <section className="card">
            <div className="card-head"><h2>Review workflow</h2></div>
            <div className="card-body">
              {steps.map((s, i) => (
                <Link key={i} to={s.to} className="row gap" style={{ padding: '6px 0', textDecoration: 'none', color: 'inherit' }}>
                  {s.done ? <CheckCircle2 size={18} color="var(--ok)" /> : <Circle size={18} color="var(--muted)" />}<span>{s.label}</span>
                </Link>
              ))}
            </div>
          </section>
          <section className="card">
            <div className="card-head"><h2>Project members</h2></div>
            <div className="card-body">
              {p.members.map((m) => <div key={m.userId} className="row gap" style={{ padding: '4px 0' }}><span className="grow">{userName(m.userId)}</span><Badge tone={m.role === 'owner' ? 'navy' : m.role === 'editor' ? 'teal' : 'neutral'}>{m.role}</Badge></div>)}
            </div>
          </section>
          <section className="card">
            <div className="card-head"><h2>History</h2></div>
            <ul className="history card-body" style={{ maxHeight: 420, overflowY: 'auto' }}>
              {[...p.history].reverse().slice(0, 60).map((h, i) => <li key={i}><span className="muted">{fmtDate(h.at)}</span><span><strong>{userName(h.by)}</strong> — {h.action}{h.detail && <div className="muted small">{h.detail}</div>}</span></li>)}
            </ul>
          </section>
        </div>
      </div>

      {members && (
        <Modal title="Project members" onClose={() => setMembers(null)} footer={<><button className="btn" onClick={() => setMembers(null)}>Cancel</button><button className="btn btn-primary" onClick={async () => { if (await mutate(() => api.put<ProjectData>(`/projects/${p.id}/members`, { members }), 'Members updated.')) setMembers(null); }}>Save members</button></>}>
          <p className="muted small">Access to an assessment requires membership. Owners manage members; editors can change content (subject to their global role); viewers are read-only.</p>
          <table className="table"><tbody>
            {users.filter((u) => !u.disabled).map((u) => {
              const m = members.find((x) => x.userId === u.id);
              return (
                <tr key={u.id}><td>{u.displayName}<div className="muted small">{ROLE_LABELS[u.role]}</div></td><td style={{ width: 160 }}>
                  <select value={m?.role ?? ''} onChange={(e) => {
                    const role = e.target.value as ProjectMember['role'] | '';
                    setMembers(role ? [...members.filter((x) => x.userId !== u.id), { userId: u.id, role }] : members.filter((x) => x.userId !== u.id));
                  }}>
                    <option value="">No access</option><option value="owner">Owner</option><option value="editor">Editor</option><option value="viewer">Viewer</option>
                  </select>
                </td></tr>
              );
            })}
          </tbody></table>
        </Modal>
      )}
      {audit && (
        <Modal title="Project audit trail" wide onClose={() => setAudit(null)}>
          <table className="table"><thead><tr><th>#</th><th>Time</th><th>User</th><th>Action</th><th>Detail</th></tr></thead><tbody>
            {audit.map((a) => <tr key={a.seq}><td className="mono">{a.seq}</td><td className="nowrap small">{fmtDate(a.at)}</td><td>{a.username}</td><td>{a.action}</td><td className="small">{a.target} {a.detail}</td></tr>)}
          </tbody></table>
        </Modal>
      )}
    </div>
  );
}
